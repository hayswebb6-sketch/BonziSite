IDC_ARROW=32512
_saved_cursor=None
_cursor_hidden=False

def set_cursor_visible(visible):
    # Windows only. macOS offers no equivalent that works without extra
    # accessibility permissions, so we leave it be.
    #
    # SetSystemCursor is used rather than ShowCursor because ShowCursor is not a
    # boolean, it is a counter: every call adjusts an internal per-thread count
    # that starts at 1, so two hides need two shows. With a random 2-5 action
    # burst that counter used to drift negative and leave the cursor stuck
    # invisible for the rest of the session. Replacing the system arrow with a
    # NULL cursor is idempotent, because we only do the swap when the stored
    # state says it is needed.
    if not IS_WINDOWS:
        return

    global _saved_cursor, _cursor_hidden
    try:
        if visible:
            if not _cursor_hidden:
                return
            if _saved_cursor:
                ctypes.windll.user32.SetSystemCursor(
                    _saved_cursor, OCR_NORMAL, IDC_ARROW
                )
            _saved_cursor=None
            _cursor_hidden=False
            return
        if _cursor_hidden:
            return
        _saved_cursor=ctypes.windll.user32.SetSystemCursor(
            None, OCR_NORMAL, IDC_ARROW
        )
        _cursor_hidden=True
    except Exception as error:
        log_error(f"cursor toggle failed: {error!r}")

def ps_quote(value):
    return "'" + value.replace("'", "''") + "'"

def _executable_and_args():
    if getattr(sys, "frozen", False):
        return sys.executable, ""
    pythonw=os.path.join(os.path.dirname(sys.executable), "pythonw.exe")
    interpreter=pythonw if os.path.exists(pythonw) else sys.executable
    return interpreter, os.path.abspath(__file__)

def add_to_startup_macos():
    # macOS autostart is a LaunchAgent plist in ~/Library/LaunchAgents.
    home=os.path.expanduser("~")
    agents=os.path.join(home, "Library", "LaunchAgents")
    label="com.bonzibuddy.app"
    plist_path=os.path.join(agents, f"{label}.plist")
    target, arguments=_executable_and_args()
    try:
        os.makedirs(agents, exist_ok=True)
        args_item=f"        <string>{arguments}</string>" if arguments else ""
        plist=(
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
            '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
            '<plist version="1.0">\n'
            "<dict>\n"
            "    <key>Label</key>\n"
            f"    <string>{label}</string>\n"
            "    <key>ProgramArguments</key>\n"
            "    <array>\n"
            f"        <string>{target}</string>\n"
            f"{args_item}\n"
            "    </array>\n"
            "    <key>RunAtLoad</key>\n"
            "    <true/>\n"
            "</dict>\n"
            "</plist>\n"
        )
        with open(plist_path, "w", encoding="utf-8") as handle:
            handle.write(plist)
        subprocess.run(["launchctl", "load", "-w", plist_path],
                       check=False, capture_output=True)
    except Exception as error:
        log_error(f"macos launch agent failed: {error!r}")

