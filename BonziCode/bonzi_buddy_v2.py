# Bonzi's app list is the same everywhere, but the command that actually opens
# each one is platform specific - notepad.exe does not exist on macOS.
#
# Two details make the difference between an app opening and a silent no-op:
#
#   - Chrome, Discord, Spotify and Steam install into per-user folders that are
#     not on PATH, so Popen("Discord.exe") raises FileNotFoundError. They are
#     resolved to a real path where we can find one.
#   - macOS goes through /usr/bin/open by absolute path. An .app started from
#     Finder is launched by launchd with a minimal PATH, and "open" has to be
#     found before it can be relied on to find anything else.
