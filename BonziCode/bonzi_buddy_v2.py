# Keeps the Tk image objects for open peek windows alive. Same reason as
# _keep_alive: a PhotoImage that goes out of scope is deleted from Tcl, and a
# Label holding a deleted image renders as an empty box.
_keep_shot_going=set()

def _capture_screen(path):
    """Grab the screen into a PNG, or raise OSError if the OS said no.

    Pillow already does this on both platforms. On macOS 10.15+ it shells out
    to screencapture, which needs Screen Recording permission, so a refusal is
    a real possibility rather than a bug.
    """
    from PIL import ImageGrab
    image=ImageGrab.grab()
    if image is None:
        raise OSError("the screen grab returned nothing")
    image.save(path, "PNG")
    return path

def _fit(photo, max_width, max_height):
    """Shrink a PhotoImage to fit a box, keeping the aspect ratio."""
    width, height=photo.width(), photo.height()
    step=1
    while True:
        new_width=width // step
        new_height=height // step
        if new_width<=max_width and new_height<=max_height:
            return photo.subsample(step, step) if step>1 else photo
        step+=1

