def _version_tuple(text):
    parts=[]
    for chunk in str(text).split("."):
        digits="".join(char for char in chunk if char.isdigit())
        parts.append(int(digits) if digits else 0)
    return tuple(parts)

manifest_sha256=""

def _download(url, dest):
    import hashlib
    import tempfile

    digest=hashlib.sha256()
    tmp=dest + ".part"
    with urllib.request.urlopen(url, timeout=60) as response, open(tmp, "wb") as out:
        while True:
            chunk=response.read(262144)
            if not chunk:
                break
            digest.update(chunk)
            out.write(chunk)
    expected=(manifest_sha256 or "").lower()
    if expected and digest.hexdigest()!=expected:
        os.remove(tmp)
        raise ValueError("checksum mismatch")
    os.replace(tmp, dest)
    return dest

def _swap_and_relaunch(new_exe):
    # A running .exe cannot overwrite itself, so a detached script retires the
    # old copy, drops the new one into place and starts it.
    import tempfile

    current=sys.executable
    backup=current + ".old"
    script=os.path.join(tempfile.gettempdir(), "bonzi_update.cmd")
    body=(
        "@echo off\r\n"
        "timeout /t 2 /nobreak >nul\r\n"
        f'move /y "{current}" "{backup}" >nul\r\n'
        f'move /y "{new_exe}" "{current}" >nul\r\n'
        f'start "" "{current}"\r\n'
        f'timeout /t 3 /nobreak >nul\r\n'
        f'del /y "{backup}" >nul\r\n'
    )
    with open(script, "w", encoding="utf-8") as handle:
        handle.write(body)
    flags=0
    if IS_WINDOWS:
        flags=getattr(subprocess, "DETACHED_PROCESS", 0) | getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
    subprocess.Popen(["cmd", "/c", script], creationflags=flags, close_fds=True)

def _bundle_path():
    """The .app bundle this code is running from, or None outside a bundle.

    sys.executable inside a bundle points at
    Bonzi Buddy.app/Contents/MacOS/Bonzi Buddy, so the bundle is whichever
    ancestor ends in .app. Walking up rather than counting three levels means a
    renamed or nested bundle still resolves.
    """
    path=os.path.abspath(sys.executable)
    while True:
        parent=os.path.dirname(path)
        if not parent or parent==path:
            return None
        if path.endswith(".app"):
            return path
        path=parent

def _swap_and_relaunch_macos(new_zip):
    """Retire the running .app and drop the downloaded one into its place.

    macOS will not let a running bundle replace itself either, so the same
    detached-script trick as Windows applies. Two differences matter:

      - The archive is unzipped, not copied. The site ships a .zip containing
        the whole bundle, because a bare .app is awkward to serve over https
        and gets mangled by Content-Disposition handling in some browsers.
      - ditto -x -k is used rather than unzip. An .app is full of symlinks and
        extended attributes; plain unzip silently drops them and the result
        launches to a blank window or not at all.
    """
    import shlex
    import tempfile

    bundle=_bundle_path()
    if bundle is None:
        log_error("macOS update: not running from a .app bundle")
        return False

    parent=os.path.dirname(bundle)
    backup=bundle + ".old"
    script=os.path.join(tempfile.gettempdir(), "bonzi_update.sh")

    # The archive root is the .app folder itself, so unpacking into the parent
    # directory recreates the bundle at exactly the same path and the open
    # below finds it.
    body=(
        "#!/bin/sh\r\n"
        "sleep 2\r\n"
        f"rm -rf {shlex.quote(backup)}\r\n"
        f"mv {shlex.quote(bundle)} {shlex.quote(backup)}\r\n"
        f"/usr/bin/ditto -x -k {shlex.quote(new_zip)} {shlex.quote(parent)}\r\n"
        f"/usr/bin/open {shlex.quote(bundle)}\r\n"
        "sleep 3\r\n"
        f"rm -rf {shlex.quote(backup)}\r\n"
    )
    with open(script, "w", encoding="ascii") as handle:
        handle.write(body)
    os.chmod(script, 0o755)

    # start_new_session detaches the updater from this process group, so the
    # shell survives Bonzi being destroyed a moment later.
    subprocess.Popen(["/bin/sh", script], start_new_session=True, close_fds=True)
    return True

