def check_for_update():
    manifest_url=_update_manifest_url()
    if not manifest_url:
        return
    if not getattr(sys, "frozen", False):
        return
    if IS_MAC and _bundle_path() is None:
        # Outside a bundle there is nothing to swap in place, and a raw binary
        # run from the Terminal is not something to silently replace.
        log_error("macOS update skipped: not running from a .app bundle")
        return
    import tempfile
    import threading

    def worker():
        global manifest_sha256
        try:
            request=urllib.request.Request(
                manifest_url, headers={"User-Agent": f"{APP_NAME}/{APP_VERSION}"}
            )
            with urllib.request.urlopen(request, timeout=15) as response:
                manifest=json.loads(response.read().decode("utf-8"))
            latest=str(manifest.get("version", "0"))
            if _version_tuple(latest)<=_version_tuple(APP_VERSION):
                return
            url=manifest.get("url")
            if not url:
                return
            if not url.lower().startswith("https://"):
                log_error("refusing update over plain http")
                return
            manifest_sha256=manifest.get("sha256", "")
            if IS_MAC:
                target=os.path.join(tempfile.gettempdir(), "bonzi_new_mac.zip")
                _download(url, target)
                if not _swap_and_relaunch_macos(target):
                    return
            else:
                target=os.path.join(tempfile.gettempdir(), "bonzi_new.exe")
                _download(url, target)
                _swap_and_relaunch(target)
            window.after(0, window.destroy)
        except Exception as error:
            log_error(f"update check failed: {error!r}")

    threading.Thread(target=worker, daemon=True).start()
