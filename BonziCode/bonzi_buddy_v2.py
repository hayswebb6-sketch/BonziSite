# ---- looking at things -----------------------------------------------------
# Bonzi can look at your screen and read what you type. Both are meant to be
# unsettling, which is the entire joke, so the constraints below are not
# incidental - they are what keeps this a novelty instead of something else:
#
#   - Nothing is written to disk. There is no keylog file and no screenshot
#     archive. Screenshots exist as one temp file that dies with the window.
#   - Nothing is sent anywhere. This section contains no network call at all.
#   - Keystrokes land in a fixed-size in-memory ring buffer and nowhere else.
#   - Both are off until something explicitly turns them on, and the window
#     doing the looking is always on screen. There is no quiet mode.
#
# The line that is deliberately not crossed is silent capture. A pet that
# records what you type and stashes it where you cannot see it is not a joke,
# it is a keylogger with a cartoon face, and the visible version lands the
# joke just as hard because you can watch him reading.

