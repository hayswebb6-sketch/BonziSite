FRONTMOST_SCRIPT=(
    'tell application "System Events" to get name of '
    "first application process whose frontmost is true"
)

def foreground_name():
    """Lowercased name or title of whatever the user is actually looking at.

    Windows gets this from pygetwindow for free. macOS needs an AppleScript
    round trip, which costs a process launch, so it is only called from the
    sensing loop and from immediately before typing - not on every animation
    frame. It can also be refused, in which case we return "" and every caller
    treats that as "I do not know", which is the safe direction: without a
    confirmed foreground we never type.
    """
    if IS_WINDOWS:
        try:
            active=pygetwindow.getActiveWindow()
        except Exception as error:
            log_error(f"could not read the active window: {error!r}")
            return ""
        if active is None:
            return ""
        return (active.title or "").strip().lower()

    if IS_MAC:
        try:
            result=subprocess.run(
                ["osascript", "-e", FRONTMOST_SCRIPT],
                capture_output=True, text=True, check=False, timeout=5,
            )
        except (OSError, subprocess.SubprocessError) as error:
            log_error(f"frontmost lookup failed: {error!r}")
            return ""
        if result.returncode!=0:
            return ""
        return result.stdout.strip().lower()

    return ""

def foreground_matches(expected):
    title=foreground_name()
    if not title:
        return False
    return any(token in title for token in expected)

def type_into_foreground(text, expected):
    time.sleep(1)

    if not foreground_matches(expected):
        log_error(f"skipped typing into unexpected window for {text!r}")
        return False

    # Imported lazily: pyautogui pulls in platform input libraries and on
    # macOS wants Accessibility permission, which we never need there.
    import pyautogui

    pyautogui.typewrite(text)
    pyautogui.press("enter")
    return True

