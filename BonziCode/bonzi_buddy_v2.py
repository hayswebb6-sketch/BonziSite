def _program_files(*parts):
    found=[]
    for name in ("ProgramFiles", "ProgramFiles(x86)"):
        root=os.environ.get(name)
        if root:
            found.append(os.path.join(root, *parts))
    return tuple(found)

def _first_existing(*paths, globs=()):
    """The first candidate that is really on this machine, else the first guess.

    Discord in particular keeps a new app-<hash> folder per update, so the glob
    has to win over the fixed guesses and the newest match has to win over the
    oldest.
    """
    for pattern in globs:
        matches=sorted(glob.glob(pattern))
        if matches:
            return matches[-1]
    for path in paths:
        if path and os.path.isfile(path):
            return path
    return next((path for path in paths if path), "")

