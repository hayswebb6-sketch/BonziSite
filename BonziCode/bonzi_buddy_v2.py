# ---- reading the keyboard --------------------------------------------------
# A fixed-size ring buffer. When it is full the oldest characters fall off the
# back, so the memory this can ever occupy is bounded no matter how long Bonzi
# runs or how fast you type.

WM_KEYDOWN=0x0100
WM_SYSKEYDOWN=0x0104
VK_BACK=0x08
VK_TAB=0x09
VK_RETURN=0x0D
VK_SHIFT=0x10
WH_KEYBOARD_LL=13

def _keylog_windows_start():
    """Low level keyboard hook on its own thread with its own message pump."""
    import ctypes
    from ctypes import wintypes

    user32=ctypes.windll.user32
    kernel32=ctypes.windll.kernel32

    user32.SetWindowsHookExW.restype=wintypes.HHOOK
    user32.SetWindowsHookExW.argtypes=[
        ctypes.c_int, ctypes.c_void_p, ctypes.c_void_p, wintypes.DWORD
    ]
    user32.CallNextHookEx.restype=ctypes.c_long
    user32.CallNextHookEx.argtypes=[
        wintypes.HHOOK, ctypes.c_int, wintypes.WPARAM, wintypes.LPARAM
    ]
    user32.PeekMessageW.argtypes=[
        ctypes.POINTER(wintypes.MSG), wintypes.HWND,
        wintypes.UINT, wintypes.UINT, wintypes.UINT,
    ]
    kernel32.GetModuleHandleW.restype=wintypes.HMODULE

    class KBDLLHOOKSTRUCT(ctypes.Structure):
        _fields_=[
            ("vkCode", wintypes.DWORD),
            ("scanCode", wintypes.DWORD),
            ("flags", wintypes.DWORD),
            ("time", wintypes.DWORD),
            ("dwExtraInfo", ctypes.POINTER(ctypes.c_ulong)),
        ]

    def on_event(ncode, wparam, lparam):
        # Must call the next hook unconditionally, including while shutting
        # down, or the whole system stops receiving keystrokes.
        if ncode>=0 and wparam in (WM_KEYDOWN, WM_SYSKEYDOWN):
            try:
                info=ctypes.cast(lparam, ctypes.POINTER(KBDLLHOOKSTRUCT)).contents
                if info.vkCode==VK_BACK:
                    _keylog_buffer.append("\b")
                elif info.vkCode==VK_TAB:
                    _keylog_buffer.append("\t")
                elif info.vkCode==VK_RETURN:
                    _keylog_buffer.append("\n")
                else:
                    state=(ctypes.c_byte * 256)()
                    user32.GetKeyboardState(state)
                    buffer=ctypes.create_unicode_buffer(8)
                    typed=user32.ToUnicode(info.vkCode, info.scanCode,
                                           state, buffer, 8, 0, None)
                    if typed>0 and buffer[0]:
                        _keylog_buffer.append(buffer[0])
            except Exception as error:
                log_error(f"keylog translate failed: {error!r}")
        return user32.CallNextHookEx(hook, ncode, wparam, lparam)

    hook_proc=ctypes.WINFUNCTYPE(
        ctypes.c_long, ctypes.c_int, wintypes.WPARAM, wintypes.LPARAM
    )(on_event)

    started=threading.Event()
    result={}

    def run():
        handle=user32.SetWindowsHookExW(
            WH_KEYBOARD_LL, hook_proc, kernel32.GetModuleHandleW(None), 0
        )
        result["hook"]=handle
        started.set()
        if not handle:
            return
        message=wintypes.MSG()
        while _keylog_active:
            # PeekMessage rather than GetMessage so the loop can notice the stop
            # flag without something having to post it a wake-up.
            while user32.PeekMessageW(
                ctypes.byref(message), None, 0, 0, 1
            ):
                user32.TranslateMessage(ctypes.byref(message))
                user32.DispatchMessageW(ctypes.byref(message))
            time.sleep(0.02)
        user32.UnhookWindowsHookEx(handle)

    thread=threading.Thread(target=run, daemon=True, name="bonzi-keylog")
    thread.start()
    started.wait(timeout=5)
    if not result.get("hook"):
        return False
    return True

def _keylog_macos_start():
    """Global key monitor through AppKit.

    Needs Accessibility permission, and returns False rather than pretending if
    it was refused, because a silently dead keylog looks exactly like a bug.
    """
    global _keylog_monitor
    try:
        from AppKit import NSEvent, NSEventMaskFlagKeyDown
    except ImportError:
        log_error("pyobjc is not installed, cannot read keys on macOS")
        return False

    def handler(event):
        characters=event.characters()
        if characters:
            _keylog_buffer.append(characters[0])

    monitor=NSEvent.addGlobalMonitorForEventsMatchingMask_handler_(
        NSEventMaskFlagKeyDown, handler
    )
    if monitor is None:
        return False
    # The monitor is a native object. If it is not retained, AppKit releases it
    # and the handler silently stops firing.
    _keylog_monitor=monitor
    return True

def _keylog_pump():
    """Redraw the keylog window from the ring buffer. Runs on the Tk thread."""
    global _keylog_active

    if not _keylog_active or _keylog_window is None:
        return

    view=_keylog_window
    if not view.winfo_exists():
        _keylog_window=None
        return

    view.text.configure(state="normal")
    view.text.delete("1.0", "end")
    view.text.insert("1.0", "".join(_keylog_buffer) or "(nothing yet)")
    view.text.configure(state="disabled")
    view.count.configure(text=f"{len(_keylog_buffer)}/{KEYLOG_LIMIT} characters")
    view.after(120, _keylog_pump)

